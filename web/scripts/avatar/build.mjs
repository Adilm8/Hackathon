// Steps 6-7 of the Story friend pipeline (docs/design/avatar-prompts.md, section 6).
// Optimises every layer in public/avatar with SVGO (MIT) and writes
// components/character/art/generated.ts: ids, boxes, fur colours and a content hash per file
// (added to the URL so browsers and the service worker pick up a re-run with the same names).
import { createHash } from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { optimize } from 'svgo';

const here = path.dirname(fileURLToPath(import.meta.url));
const web = path.resolve(here, '../..');
const pub = path.join(web, 'public', 'avatar');
const cfg = JSON.parse(fs.readFileSync(path.join(here, 'ids.json'), 'utf8'));
const colors = JSON.parse(fs.readFileSync(path.join(here, 'colors.json'), 'utf8'));
const manifest = JSON.parse(fs.readFileSync(path.join(here, '.cache', 'manifest.json'), 'utf8'));

const svgoConfig = {
  multipass: true,
  floatPrecision: 1,
  plugins: ['preset-default'],
};

let total = 0;
let biggest = ['', 0];
const hashes = {};
for (const level of fs.readdirSync(pub)) {
  for (const file of fs.readdirSync(path.join(pub, level))) {
    const full = path.join(pub, level, file);
    if (file.endsWith('.svg')) {
      const out = optimize(fs.readFileSync(full, 'utf8'), { ...svgoConfig, path: full }).data;
      fs.writeFileSync(full, out);
    }
    const buf = fs.readFileSync(full);
    total += buf.length;
    if (buf.length > biggest[1]) biggest = [`${level}/${file}`, buf.length];
    hashes[`${level}/${file}`] = createHash('sha1').update(buf).digest('hex').slice(0, 8);
  }
}

const levels = {};
const sheetsDir = path.resolve(web, '..', 'docs', 'design', 'avatar', 'sheets');
for (const [key, sheet] of Object.entries(cfg.sheets)) {
  const level = sheet.level ?? key;
  if (key === 'template') continue;
  if (sheet.optional && !fs.existsSync(path.join(sheetsDir, sheet.file))) continue;
  levels[level] ??= {};
  for (const id of sheet.ids) {
    const m = manifest[level]?.[id] ?? {};
    const ext = level === 'backdrop' ? 'webp' : 'svg';
    const variants = {};
    for (const f of Object.keys(hashes)) {
      const [lv, name] = f.split('/');
      if (lv !== level) continue;
      const base = name.replace(/\.(svg|webp)$/, '');
      if (base === id) variants.default = hashes[f];
      else if (base.startsWith(`${id}--`)) variants[base.slice(id.length + 2)] = hashes[f];
    }
    levels[level][id] = {
      ext,
      v: variants,
      ...(m.bbox ? { bbox: m.bbox } : {}),
      ...(m.fur ? { fur: m.fur } : {}),
      ...(sheet.behind?.includes(id) ? { behind: true } : {}),
    };
  }
}

const ts = `// Generated by web/scripts/avatar/build.mjs from docs/design/avatar/sheets. Do not edit by hand:
// change the sheets or the scripts and run \`npm run avatar\`.

export const AVATAR_CANVAS = ${JSON.stringify(cfg.canvas)} as const;

export const CLOTHES_SWATCH = ${JSON.stringify(colors.clothes, null, 1)} as const;

export const AVATAR_ART = ${JSON.stringify(levels, null, 1)} as const;
`;
fs.mkdirSync(path.join(web, 'components', 'character', 'art'), { recursive: true });
fs.writeFileSync(path.join(web, 'components', 'character', 'art', 'generated.ts'), ts);
console.log(`avatar: ${Object.keys(hashes).length} files, ${(total / 1024).toFixed(0)} KB total, biggest ${biggest[0]} ${(biggest[1] / 1024).toFixed(1)} KB`);
